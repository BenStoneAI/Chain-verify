export const proofProductOrder: ProofProductSlug[] = ['invoiceproof', 'audit-proof', 'verify-api'];

export function getProofProductMarketing(slug: ProofProductSlug) {
  return proofProductMarketing[slug];
}

export function getProofProductsMarketing() {
  return proofProductOrder.map((slug) => proofProductMarketing[slug]);
}

export function generateProofMarketingSnapshot() {
  return getProofProductsMarketing().map((product) => ({
    product: product.name,
    route: product.route,
    label: product.sample.label,
    sampleProofId: product.sample.proofId,
    claim: product.claim,
    proofFormat: product.proofFormat,
    limitations: product.limitations,
    evidenceSnippets: product.sample.evidenceSnippets.map((snippet) => snippet.title),
  }));
}

